const zoneProduits = document.getElementById("produits");
const recherche = document.getElementById("search");

const popup = document.getElementById("popup");
const fermer = document.getElementById("fermer");

const imageProduit = document.getElementById("imageProduit");
const nomProduit = document.getElementById("nomProduit");
const prixProduit = document.getElementById("prixProduit");

const boutonPanier = document.getElementById("ajouterPanier");


let produitChoisi = null;
let tailleChoisie = null;



function afficherProduits(liste){

    zoneProduits.innerHTML = "";

    liste.forEach(produit => {

        zoneProduits.innerHTML += `

        <div class="carte-produit" onclick="ouvrirProduit(${produit.id})">

            <img src="${produit.image}" alt="${produit.nom}">

            <h3>${produit.nom}</h3>

            <p>${produit.prix.toLocaleString("fr-FR")} FCFA</p>

        </div>

        `;

    });

}


afficherProduits(produits);



function ouvrirProduit(id){

    produitChoisi = produits.find(p => p.id === id);

    imageProduit.src = produitChoisi.image;
    nomProduit.textContent = produitChoisi.nom;
    prixProduit.textContent = produitChoisi.prix.toLocaleString("fr-FR")+" FCFA";

    tailleChoisie = null;

    popup.style.display="flex";

}



fermer.onclick = function(){

    popup.style.display="none";

};



document.querySelectorAll(".tailles button").forEach(button => {

    button.onclick = function(){

        tailleChoisie = this.textContent;

        document.querySelectorAll(".tailles button")
        .forEach(btn => btn.style.background="#111");

        this.style.background="#ff0080";

    };

});



boutonPanier.onclick = function(){

    if(!tailleChoisie){

        alert("Choisissez une taille");

        return;

    }


    let panier = JSON.parse(localStorage.getItem("panier")) || [];


    panier.push({

        nom: produitChoisi.nom,
        prix: produitChoisi.prix,
        image: produitChoisi.image,
        taille: tailleChoisie,
        quantite:1

    });


    localStorage.setItem("panier", JSON.stringify(panier));
     
    mettreAJourCompteur();

    alert("Produit ajouté au panier 🛒");


    popup.style.display="none";

};




recherche.addEventListener("input",()=>{

    let texte = recherche.value.toLowerCase();


    let resultat = produits.filter(produit =>

        produit.nom.toLowerCase().includes(texte)

    );


    afficherProduits(resultat);

});

function mettreAJourCompteur(){

    let panier = JSON.parse(localStorage.getItem("panier")) || [];

    let compteur = document.getElementById("nombrePanier");

    if(compteur){

        compteur.textContent = panier.length;

    }

}


mettreAJourCompteur();
